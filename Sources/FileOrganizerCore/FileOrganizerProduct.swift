import Foundation

/// Описывает неизменяемые сведения о продукте, доступные UI и будущему MCP-мосту.
///
/// Тип размещён в Core, чтобы разные исполняемые цели сообщали одинаковое имя и
/// версию. Это исключает расхождение представления продукта между приложением и
/// внешним локальным адаптером, когда они начнут обмениваться сообщениями.
public enum FileOrganizerProduct {
    /// Пользовательское имя, которое будет выводиться в интерфейсе и отчётах.
    public static let displayName = "Ares"

    /// Начальная версия каркаса. Семантическое значение будет увеличиваться при
    /// выпуске функций, а не при каждой локальной сборке.
    public static let version = "0.1.0"
}
